#!/usr/bin/env python3
"""Regenerates src/hangul.rs: the Galmuri glyphs for every Korean letter the firmware uses.

    tools/make_hangul.py path/to/Galmuri9.bdf path/to/Galmuri11.bdf
"""
import pathlib
import re
import sys

ROWS = 13
root = pathlib.Path(__file__).resolve().parent.parent
output = root / "src" / "hangul.rs"

wanted = set()
for source in (root / "src").glob("*.rs"):
    if source != output:
        wanted.update(re.findall(r"[가-힣]", source.read_text(encoding="utf-8")))



def path_name(path):
    return pathlib.Path(path).stem


# Blank rows the font leaves above its letters, trimmed so they sit at the top of the line.
LEAD = {"Galmuri9": 0, "Galmuri11": 3}


def glyph_table(path):
    text = pathlib.Path(path).read_text(encoding="latin-1")
    ascent = int(re.search(r"FONT_ASCENT (\d+)", text).group(1))
    glyphs = []
    for block in re.findall(r"STARTCHAR.*?ENDCHAR", text, re.S):
        code = int(re.search(r"ENCODING (-?\d+)", block).group(1))
        if code < 0 or chr(code) not in wanted:
            continue
        advance = int(re.search(r"DWIDTH (\d+)", block).group(1))
        box = re.search(r"BBX (-?\d+) (-?\d+) (-?\d+) (-?\d+)", block).groups()
        _, height, left, bottom = map(int, box)
        data = block.split("BITMAP")[1].split("ENDCHAR")[0].split()
        rows = [0] * ROWS
        top = max(ascent - height - bottom - LEAD[path_name(path)], 0)
        for index, line in enumerate(data):
            bits = int(line, 16) << (16 - len(line) * 4)
            rows[top + index] = bits >> left & 0xFFFF
        glyphs.append((chr(code), advance, rows))
    missing = wanted - {glyph[0] for glyph in glyphs}
    if missing:
        sys.exit(f"not in the font: {sorted(missing)}")
    return sorted(glyphs)


lines = [
    "//! Generated by tools/make_hangul.py from Galmuri (SIL OFL 1.1, see fonts/Galmuri-OFL.txt).",
    "",
    f"pub const ROWS: usize = {ROWS};",
    "pub type Glyph = (char, u8, [u16; ROWS]);",
]
for name, path in (("SMALL", sys.argv[1]), ("LARGE", sys.argv[2])):
    lines += ["", f"pub const {name}: &[Glyph] = &["]
    for character, advance, rows in glyph_table(path):
        body = ", ".join(f"0x{row:04x}" for row in rows)
        lines.append(f"    ('{character}', {advance}, [{body}]),")
    lines.append("];")
output.write_text("\n".join(lines) + "\n", encoding="utf-8")
